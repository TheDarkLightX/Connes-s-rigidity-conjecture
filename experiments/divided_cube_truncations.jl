using JSON

const P = 3

modp(x) = mod(x, P)
invp(x) = x % P == 1 ? 1 : 2

function rref_mod(A::Matrix{Int})
    R = modp.(copy(A))
    rows, cols = size(R)
    pivots = Int[]
    r = 1
    for c in 1:cols
        r > rows && break
        pivot = findfirst(i -> R[i,c] != 0, r:rows)
        pivot === nothing && continue
        i = r - 1 + pivot
        R[r,:], R[i,:] = copy(R[i,:]), copy(R[r,:])
        R[r,:] .= modp.(R[r,:] .* invp(R[r,c]))
        for j in 1:rows
            if j != r && R[j,c] != 0
                factor = R[j,c]
                R[j,:] .= modp.(R[j,:] .- factor .* R[r,:])
            end
        end
        push!(pivots, c)
        r += 1
    end
    R, pivots
end

rank_mod(A::Matrix{Int}) = length(last(rref_mod(A)))

function independent_columns(A::Matrix{Int})
    _, pivots = rref_mod(A)
    isempty(pivots) ? zeros(Int, size(A,1), 0) : A[:,pivots]
end

function multiset_triples(m::Int)
    [(a,b,c) for a in 0:m-1 for b in a:m-1 for c in b:m-1]
end

function unique_permutations(t::NTuple{3,Int})
    a,b,c = t
    collect(Set([(a,b,c),(a,c,b),(b,a,c),(b,c,a),(c,a,b),(c,b,a)]))
end

function transvection_matrix(N::Int, i::Int, j::Int, k::Int)
    m = 3N
    L = Matrix{Int}(I, m, m)
    for d in 0:(N-k-1)
        src = j*N + d + 1
        dst = i*N + d + k + 1
        L[dst,src] = modp(L[dst,src] + 1)
    end
    L
end

function divided_cube_action(N::Int, L::Matrix{Int})
    m = 3N
    triples = multiset_triples(m)
    row_of = Dict(t => q for (q,t) in enumerate(triples))
    D = length(triples)
    A = zeros(Int, D, D)
    nonzero_rows = [findall(!iszero, L[:,s]) for s in 1:m]

    for (col,t) in enumerate(triples)
        for s in unique_permutations(t)
            left = nonzero_rows[s[1]+1]
            middle = nonzero_rows[s[2]+1]
            right = nonzero_rows[s[3]+1]
            for a1 in left, b1 in middle, c1 in right
                a,b,c = a1-1,b1-1,c1-1
                a <= b <= c || continue
                coefficient = modp(L[a1,s[1]+1] * L[b1,s[2]+1] * L[c1,s[3]+1])
                coefficient == 0 && continue
                row = row_of[(a,b,c)]
                A[row,col] = modp(A[row,col] + coefficient)
            end
        end
    end
    A, triples
end

function orbit_span_dimension(generators::Vector{Matrix{Int}}, v::Vector{Int})
    basis = reshape(modp.(v), :, 1)
    while true
        olddim = size(basis,2)
        candidates = [basis]
        for g in generators
            push!(candidates, modp.(g * basis))
        end
        nextbasis = independent_columns(hcat(candidates...))
        size(nextbasis,2) == olddim && return olddim
        basis = nextbasis
    end
end

function analyze_truncation(N::Int)
    m = 3N
    triples = multiset_triples(m)
    row_of = Dict(t => q for (q,t) in enumerate(triples))
    generators = Matrix{Int}[]
    for i in 0:2, j in 0:2
        i == j && continue
        for k in 0:N-1
            action, _ = divided_cube_action(N, transvection_matrix(N,i,j,k))
            push!(generators, action)
        end
    end

    D = length(triples)
    identityD = Matrix{Int}(I,D,D)
    fixed_equations = vcat([modp.(g - identityD) for g in generators]...)
    fixed_dimension = D - rank_mod(fixed_equations)

    pure = zeros(Int,D)
    pure[row_of[(0,0,0)]] = 1
    mixed = zeros(Int,D)
    mixed[row_of[(0,N,2N)]] = 1

    pure_span = orbit_span_dimension(generators,pure)
    mixed_span = orbit_span_dimension(generators,mixed)
    kernel_dimension = D-m

    Dict(
        "N" => N,
        "vector_dimension" => m,
        "divided_cube_dimension" => D,
        "frobenius_kernel_dimension" => kernel_dimension,
        "generator_count" => length(generators),
        "common_fixed_subspace_dimension" => fixed_dimension,
        "pure_cube_orbit_span_dimension" => pure_span,
        "all_distinct_orbit_span_dimension" => mixed_span,
        "pure_cube_is_cyclic" => pure_span == D,
        "all_distinct_generates_frobenius_kernel" => mixed_span == kernel_dimension,
        "no_common_fixed_vector" => fixed_dimension == 0
    )
end

function main()
    results = [analyze_truncation(N) for N in 1:4]
    output = Dict(
        "field" => "F_3",
        "module" => "span of pure cubes in ((F_3[t]/(t^N))^3)^(tensor 3)",
        "generators" => "elementary transvections I + t^k E_ij for i != j and 0 <= k < N",
        "kernel_generator" => "the all-distinct orbit sum indexed by (e_1,e_2,e_3) in degree zero",
        "results" => results,
        "conjectural_family_statement" => (
            "For V=F[t]^3, the divided-cube module is cyclic under E_3(F[t]) generated by e_1^tensor3, " *
            "and ker(d_3) is cyclic generated by Sym(e_1 tensor e_2 tensor e_3); every nonzero divided cube has infinite orbit."
        ),
        "claim_boundary" => "Finite truncation evidence for N=1..4; not a proof over F_3[t]."
    )
    open("experiments/divided_cube_truncations_result.json","w") do io
        JSON.print(io,output,2)
    end
    println(JSON.json(output))
    @assert all(r -> r["no_common_fixed_vector"], results)
    @assert all(r -> r["pure_cube_is_cyclic"], results)
    @assert all(r -> r["all_distinct_generates_frobenius_kernel"], results)
end

main()
